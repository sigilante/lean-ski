"""Emit Lean from skijack: the Scott constructors of SKIlark's compiled kernel
with their elimination lemmas and the compiled kernel words (Ski/Scott.lean),
and a small conformance corpus of terms with the reference reducer's
contraction counts plus a canonicity test per word (Ski/Corpus.lean).  Run from the SKIlark venv:

    python scripts/emit.py

Every lemma is proved by `iter_sound rfl`: the kernel re-runs the same
contractions the reference reducer took, on symbolic arguments.
"""
import sys, pathlib
sys.path.insert(0, "/Users/neal/SKIlark")
import skijack
from skijack.run import run_level0
from aviary_kernel.terms import App, Atom
from skilark import joy

OUT = pathlib.Path(__file__).resolve().parent.parent / "Ski"


def lean(t):
    if isinstance(t, Atom):
        return t.name
    return f"({lean(t.fn)} ⬝ {lean(t.arg)})"


def whnf_shape(term, args):
    """Apply `term` to fresh atoms and reduce to whnf on the host; return the
    shape (with the atoms as free variables) and the contraction count."""
    t = term
    for a in args:
        t = App(t, Atom(a))
    r = run_level0(t, 10_000)
    assert r.status.name == "WHNF", r.status
    return lean(r.term), r.steps


e = skijack.compile(joy.compiled({"p": "1 2 + dup +"}))

#: the compiled kernel words, in Joy's order
WORDS = ["wDup", "wSwap", "wPop", "wQcons", "wCat", "wUnit", "wDip", "wDo",
         "wIfz", "wLit", "wQuote", "wAdd"]

#: the kernel's helpers the proofs name: numeral addition (inlined into
#: wAdd) and composition
HELPERS = ["add", "seq", "idW"]
types = {name: decl for name, decl in e.types.items()}

# ---------------------------------------------------------------- Scott.lean
lines = ['import Ski.Fuel', 'open Term', '',
         '/-!', '# Scott constructors, as SKIjack compiles them',
         '',
         'Generated by `scripts/emit.py` from `skijack` 0.2.0; do not edit.  Each',
         'constructor is the closed term the compiler emits, and each elimination',
         'lemma is the reference reducer\'s own contraction sequence on symbolic',
         'arguments, re-run by the kernel (`iter_sound rfl`).  The continuation',
         'receives the fields as unreduced applications — `K ⬝ n ⬝ s` for `n` —',
         'which is what bracket abstraction produces and what every word-level',
         'proof has to reason through.', '-/', '', 'namespace Scott', '']
for tname in ["nat", "item", "stack", "quot", "result"]:
    decl = types[tname]
    ctors = [c.name for c in decl.ctors]
    lines.append(f"-- {tname} === " + " | ".join(
        c.name + "".join(" " + f for f in c.fields) for c in decl.ctors))
    for c in decl.ctors:
        lines.append(f"def {c.name} : Term := {lean(e.terms[c.name])}")
    lines.append("")
    for c in decl.ctors:
        fields = [f"x{i}" for i in range(len(c.fields))]
        conts = [f"k{j}" for j in range(len(ctors))]
        shape, n = whnf_shape(e.terms[c.name], fields + conts)
        binders = " ".join(fields + conts)
        lhs = " ⬝ ".join([c.name] + fields + conts)
        lines.append(f"theorem {c.name}_elim ({binders} : Term) :")
        lines.append(f"    Steps ({lhs}) {shape} :=")
        lines.append(f"  iter_sound (k := {n}) rfl")
        lines.append("")
lines += ["-- The kernel words, compiled (skilark.joy.COMPILED_KERNEL).  `wDip`, `wDo`",
          "-- and `wIfz` take the quotation eliminator `ap` first; `wLit` and `wQuote`",
          "-- take their literal first.  `wQcons`, `wCat` and `wUnit` build `quot`",
          "-- values, so their terms depend on the program's count of static",
          "-- quotations; these are the terms for a program with none.", ""]
for w in WORDS:
    lines.append(f"def {w} : Term := {lean(e.terms[w])}")
lines += ["", "-- The kernel's helpers: `add` (inlined into `wAdd`) and composition.", ""]
for w in HELPERS:
    lines.append(f"def {w} : Term := {lean(e.terms[w])}")
lines.append("")
lines.append("end Scott")
(OUT / "Scott.lean").write_text("\n".join(lines) + "\n", encoding="utf-8")

# --------------------------------------------------------------- Corpus.lean
progs = {"p": "1 2 + dup +", "q": "3 [dup +] i", "r": "1 2 over"}
c = skijack.compile(joy.compiled(progs))
i = skijack.compile(joy.interpreted(progs))
rows = []
for label, exp, names in [("compiled", c, ["up", "uq", "ur"]), ("interpreted", i, ["up", "uq", "ur"])]:
    for n in names:
        r = run_level0(exp.terms[n], 5_000_000)
        rows.append((f"{label}_{n}", lean(exp.terms[n]), r.steps, progs[n[1:]]))
lines = ['import Ski.Fuel', 'import Ski.Scott', 'import Ski.Composition', 'open Term', '',
         '/-!', '# Conformance corpus',
         '',
         'Generated by `scripts/emit.py`; do not edit.  SKIlark programs in both',
         'forms, compiled by `skijack` 0.2.0, with the contraction count the',
         'reference reducer reports.  `Main.lean` runs `runF` on each and fails',
         'if a count differs: the Lean interpreter and the reference reducer',
         'must agree contraction for contraction.',
         '',
         'The canonicity tests compare each word term in `Ski/Scott.lean` with',
         'the term the same word compiles to inside the corpus programs, whose',
         'quotation sum has two static constructors.  Nine words compile to the',
         'same term in both; `wQcons`, `wCat` and `wUnit` build `quot` values',
         'and so differ, and their tests record the difference.',
         '',
         'The program tests pin `N` against the compiler: for each corpus',
         'program without bracketed quotations, the compiled program applied to',
         'a symbolic eliminator reduces to `N` of its word list.', '-/', '',
         'structure Row where', '  name : String', '  joy : String', '  term : Term',
         '  steps : Nat', '']
for name, term, steps, src in rows:
    lines.append(f"def {name} : Term := {term}")
lines.append("")
lines.append("def corpus : List Row := [")
lines.append(",\n".join(f'  ⟨"{name}", "{src}", {name}, {steps}⟩' for name, _, steps, src in rows))
lines.append("]")
lines += ["", "-- canonicity: the pasted word terms against the corpus compilation", ""]
for w in WORDS + HELPERS:
    lines.append(f"def corpus_{w} : Term := {lean(c.terms[w])}")
lines.append("")
for w in WORDS + HELPERS:
    if e.terms[w] == c.terms[w]:
        lines.append(f"theorem canon_{w} : Scott.{w} = corpus_{w} := rfl")
    else:
        lines.append(f"theorem canon_{w}_differs : Scott.{w} ≠ corpus_{w} := by decide")

# programs: the compiled body, applied to a symbolic eliminator, is N of the words
LEAN_WORD = {"dup": ".dup", "swap": ".swap", "pop": ".pop", "cons": ".cons",
             "cat": ".cat", "unit": ".unit", "dip": ".dip", "i": ".i",
             "ifz": ".ifz", "+": ".add"}


def n_term(ws, apx):
    """`N` of Ski/Composition.lean, on the host."""
    def word(w):
        if isinstance(w, int):
            t = c.terms["Zero"]
            for _ in range(w):
                t = App(c.terms["Suc"], t)
            return App(c.terms["wLit"], t)
        t = c.terms["w" + joy.KERNEL[w]]
        return App(t, apx) if w in ("dip", "i", "ifz") else t
    if not ws:
        return c.terms["idW"]
    out = word(ws[-1])
    for w in reversed(ws[:-1]):
        out = App(App(c.terms["seq"], word(w)), out)
    return out


lines += ["", "-- programs: the compiled body is N of its word list", ""]
for pname, src in progs.items():
    ws = joy.expand(joy.parse(src), joy.DEFINITIONS)
    if any(isinstance(w, list) for w in ws):
        continue
    apx = Atom("apT")
    t, target, k = App(c.terms["c" + pname], apx), n_term(ws, apx), 0
    while t != target:
        r = run_level0(t, 1)
        assert r.steps == 1, f"c{pname} ap does not reach N"
        t, k = r.term, k + 1
    words = ", ".join(f".lit {w}" if isinstance(w, int) else LEAN_WORD[w] for w in ws)
    lines.append(f"def corpus_c{pname} : Term := {lean(c.terms['c' + pname])}")
    lines.append("")
    lines.append(f"/-- `{src}` -/")
    lines.append(f"theorem compiled_c{pname}_N (apT : Term) :")
    lines.append(f"    Steps (corpus_c{pname} ⬝ apT) (N apT [{words}]) :=")
    lines.append(f"  iter_sound (k := {k}) rfl")
(OUT / "Corpus.lean").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("Scott.lean:", (OUT / "Scott.lean").stat().st_size, "bytes; Corpus.lean:", (OUT / "Corpus.lean").stat().st_size, "bytes")
print("counts:", [(n, s) for n, _, s, _ in rows])
