# ---------------------------------------------------------------- Table.lean
# Quotation tables: one per compilation, as data, each term checked against
# the kernel's compilation of its source; the laws are Ski/Laws.lean's.
LEAN_WORD = {"dup": ".dup", "swap": ".swap", "pop": ".pop", "cons": ".cons",
             "cat": ".cat", "unit": ".unit", "dip": ".dip", "i": ".i",
             "ifz": ".ifz", "+": ".add"}
def lean_words(ws, quot_index):
    out = []
    for w in ws:
        if isinstance(w, int):
            out.append(f".lit {w}")
        elif isinstance(w, list):
            out.append(f".quote (.stat {quot_index(w)})")
        else:
            out.append(LEAN_WORD[w])
    return "[" + ", ".join(out) + "]"


def cw_host(w, S):
    """`cw (fun _ _ => .err)` of `Ski/Words.lean`, on the host: the words that
    run no quotation."""
    def q(t):
        return isinstance(t, tuple) and t[0] == "quot"
    if isinstance(w, int):
        return ("val", [("num", w)] + S)
    if isinstance(w, tuple):
        return ("val", [("quot", w[1])] + S)
    if w == "dup" and len(S) >= 1:
        return ("val", [S[0], S[0]] + S[1:])
    if w == "swap" and len(S) >= 2:
        return ("val", [S[1], S[0]] + S[2:])
    if w == "pop" and len(S) >= 1:
        return ("val", S[1:])
    if w == "cons" and len(S) >= 2 and q(S[0]):
        return ("val", [("quot", ("cons", S[1], S[0][1]))] + S[2:])
    if w == "cat" and len(S) >= 2 and q(S[0]) and q(S[1]):
        return ("val", [("quot", ("cons", S[1], ("then", S[0][1])))] + S[2:])
    if w == "unit" and len(S) >= 1:
        return ("val", [("quot", ("unit", S[0]))] + S[1:])
    if w == "+" and len(S) >= 2 and S[0][0] == "num" and S[1][0] == "num":
        return ("val", [("num", S[0][1] + S[1][1])] + S[2:])
    return ("err", None)


def run_derivation(ws, S, body):
    """A derivation of `Run (.prog ws) S o` in `Ski/Apply.lean`, built on the
    host and emitted as a Lean term for the kernel to check, with its
    outcome.  Quotations are ('stat', k) | ('cons', x, r) | ('unit', x) |
    ('then', r); a static quotation's words are `body(k)`, and the word
    ('quote', q) pushes `q`."""
    def quot(q, S):
        if q[0] == "stat":
            o, pf = prog(body(q[1]), S)
            return o, f".stat (k := {q[1]}) (by decide) ({pf})"
        if q[0] == "cons":
            o, pf = quot(q[2], [q[1]] + S)
            return o, f".cons ({pf})"
        if q[0] == "unit":
            return ("val", [q[1]] + S), ".unit"
        if S and S[0][0] == "quot":
            o1, pf1 = quot(S[0][1], S[1:])
            if o1[0] == "err":
                return o1, f".then_err ({pf1})"
            o2, pf2 = quot(q[1], o1[1])
            return o2, f".then_val ({pf1}) ({pf2})"
        return ("err", None), ".then_bad (fun _ _ e => by cases e)"
    def word(w, S):
        if w == "i":
            if S and S[0][0] == "quot":
                o, pf = quot(S[0][1], S[1:])
                return o, f".i_run ({pf})"
            return ("err", None), ".i_bad (fun _ _ e => by cases e)"
        if w == "dip":
            if len(S) >= 2 and S[0][0] == "quot":
                o, pf = quot(S[0][1], S[2:])
                return (("val", [S[1]] + o[1]) if o[0] == "val" else o), f".dip_run ({pf})"
            return ("err", None), ".dip_bad (fun _ _ _ e => by cases e)"
        if w == "ifz":
            if (len(S) >= 3 and S[0][0] == "quot" and S[1][0] == "quot" and S[2][0] == "num"):
                if S[2][1] == 0:
                    o, pf = quot(S[1][1], S[3:])
                    return o, f".ifz_zero ({pf})"
                o, pf = quot(S[0][1], [("num", S[2][1] - 1)] + S[3:])
                return o, f".ifz_succ ({pf})"
            return ("err", None), ".ifz_bad (fun _ _ _ _ e => by cases e)"
        return cw_host(w, S), ".plain rfl"
    def prog(ws, S):
        if not ws:
            return ("val", S), ".nil _"
        o, pw = word(ws[0], S)
        if o[0] == "err":
            return o, f".seq_err ({pw})"
        o2, pr = prog(ws[1:], o[1])
        return o2, f".seq_val ({pw}) ({pr})"
    return prog(ws, S)


def quotation_table(programs):
    """The compiler's static quotations for a program set, in hoisting order."""
    comp = joy._Compiler()
    for prog in joy._programs(programs, joy.DEFINITIONS).values():
        comp.body(prog)
    i = 0
    while i < len(comp.quots):
        comp.body(comp.quots[i])
        i += 1
    return comp.quots, (lambda q: comp.index[joy.words(q)] - 1)


def lt_absurd(n):
    return f"absurd h (by show ¬ (_ + {n} < {n}); omega)"


def by_index(n, arms, fallback):
    """`match k, hk with | 0, _ => … | n-1, _ => … | _ + n, h => absurd`."""
    if n == 0:
        return f"fun k hk => absurd hk (Nat.not_lt_zero k)" if fallback else None
    cases = "".join(f"\n      | {k}, _ => {arm}" for k, arm in enumerate(arms))
    return f"fun k hk => match k, hk with{cases}\n      | _ + {n}, h => {lt_absurd(n)}"


def lean_item(x):
    return f".num {x[1]}" if x[0] == "num" else "(.quot _)"


def emit_table(ns, doc, X, quots, qidx, names, programs, text, rows=None, runs=()):
    T = X.terms
    n = len(quots)
    L = [f"namespace {ns}", "", f"/-! {doc} -/", ""]
    for k in range(n):
        L.append(f"def Q{k + 1} : Term := {lean(T[f'Q{k + 1}'])}")
    for field in ["QCons", "QUnit", "QThen", "wQcons", "wCat", "wUnit", "applyU"]:
        if names[field] == field:
            L.append(f"def {field} : Term := {lean(T[field])}")
    if names["QCons"] == "QCons":
        L.append("")
        m = n + 3
        for k in range(n):
            L += ctor_abs(f"Q{k + 1}", T[f"Q{k + 1}"], 0, k, m)
        L += ctor_abs("QCons", T["QCons"], 2, n, m)
        L += ctor_abs("QUnit", T["QUnit"], 1, n + 1, m)
        L += ctor_abs("QThen", T["QThen"], 1, n + 2, m)
    for k in range(n):
        L.append(f"def b{k + 1} : Term := {lean(T[f'b{k + 1}'])}")
    if n:
        L.append("")
    # the table as data, and its kit compiled from source, term for term
    body = "fun _ => []" if n == 0 else "fun k => match k with" + "".join(
        f" | {k} => {lean_words(quots[k], qidx)}" for k in range(n)) + " | _ => []"
    ref = lambda field: names[field] if names[field] != field else field
    L += [f"def table : Table := ⟨{n}, {body}⟩", ""]
    for k in range(n):
        L.append(f"theorem table_Qs{k} : table.Qs {k} = Q{k + 1} := by decide +kernel")
    for field in ["QCons", "QUnit", "QThen", "wQcons", "wCat", "wUnit", "applyU"]:
        L.append(f"theorem table_{field} : table.{field} = {ref(field)} := by decide +kernel")
    for k in range(n):
        L.append(f"theorem table_bodyT{k} : table.bodyT {k} = b{k + 1} := by decide +kernel")
    L += ["", "/-- Every static quotation's body is valid over the table. -/",
          f"theorem table_valid : table.Valid := {by_index(n, ['rfl' for _ in range(n)], True)}", "",
          "scoped instance kit : Kit := table.kit",
          "scoped instance elim : KitElim := table.kit_elim",
          "scoped instance words : KitWords := table.kit_words",
          "scoped instance apply : KitApply := table.kit_apply table_valid", ""]
    # programs whose quotations are all in this table, each the kernel's
    # compilation of its words
    for pname, src in programs.items():
        ws = joy.expand(joy.parse(src), joy.DEFINITIONS)
        L += [f"def c{pname} : Term := {lean(T['c' + pname])}", "",
              f"/-- `{src}`: `skijack`'s term is the kernel's compilation of its words. -/",
              f"theorem c{pname}_eq : c{pname} = table.progT {lean_words(ws, qidx)} := by",
              "  decide +kernel", ""]
        if pname in runs:
            # a bracketed quotation is its static index
            def lit(ws):
                return [("quote", ("stat", qidx(w))) if isinstance(w, list) else w for w in ws]
            o, pf = run_derivation(lit(ws), [], lambda k: lit(quots[k]))
            assert o[0] == "val" and all(x[0] == "num" for x in o[1]), o
            final = "[" + ", ".join(lean_item(x) for x in o[1]) + "]"
            assert final == runs[pname], (final, runs[pname])
            L += [f"/-- `{src}` on the empty stack: its derivation, built on the host. -/",
                  f"theorem c{pname}_run : Run (.prog {lean_words(ws, qidx)}) [] (.val {final}) :=",
                  f"  {pf}", ""]
    # the corpus rows are these programs, run with this table's applyU on the empty stack
    for pname in (programs if rows else []):
        assert T["u" + pname] == App(App(T["c" + pname], T["applyU"]), T["Empty"])
        L += [f"/-- The corpus row `{rows}_u{pname}` is `c{pname}` run with this table's `applyU`",
              "    on the empty stack. -/",
              f"theorem {rows}_u{pname}_eq : {rows}_u{pname} = c{pname} ⬝ Kit.applyU ⬝ encStack [] := by",
              "  decide +kernel", ""]
    # the front end, on this compilation's whole source
    front = [(f"Q{k + 1}", f"Q{k + 1}") for k in range(n)]
    front += [(f, ref(f)) for f in ["QCons", "QUnit", "QThen", "wQcons", "wCat", "wUnit", "applyU"]]
    front += [(f"b{k + 1}", f"b{k + 1}") for k in range(n)]
    front += [(f"c{p}", f"c{p}") for p in programs]
    if rows:
        front += [(f"u{p}", f"{rows}_u{p}") for p in programs]
    L += ["/-- The front end reads this compilation's source (`" + text + "`,",
          "    `Ski/Source.lean`) and compiles it to every term `skijack` emitted for it. -/",
          "theorem front_agrees :",
          "    [" + ", ".join(f'nm! "{a}"' for a, _ in front) + "].map",
          f"      (Front.termOf (Front.compileFile {text})) =",
          "    [" + ", ".join(f"some {b}" for _, b in front) + "] := by",
          "  decide +kernel", ""]
    L += [f"end {ns}", ""]
    return L


