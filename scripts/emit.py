# The Lean front end's level-0 coverage: files `skijack` compiles, in both
# lexicons, checked term for term; and programs `skijack` refuses, refused.
import re as _re

CORPUS = pathlib.Path.home() / "skijack/python/skijack/corpus"


def to_unicode(t):
    """The coverage file's Unicode spelling (`skijack/lexicon.py`)."""
    t = (t.replace("===", "≡").replace(":=", "≔").replace("|>", "▹").replace("->", "→")
         .replace("\\", "λ").replace("--", "⍝"))
    t = _re.sub(r"(\d+)@", r"\1⊑", t)
    for a, b in [("B", "∘"), ("C", "⇄"), ("W", "⋈"), ("Y", "Υ")]:
        t = _re.sub(r"(?<![A-Za-z0-9_'])" + a + r"(?![A-Za-z0-9_'])", b, t)
    return t


cov_text = (pathlib.Path(__file__).resolve().parent / "coverage.ski").read_text(encoding="utf-8")
SUITES = [  # (Lean name, doc, ascii text, unicode text)
    ("coverage", "the coverage file `scripts/coverage.ski`: signatures, the ISA, Tier 1, the prelude, λ, cells, axis picks, case, cores and an interpreter core",
     cov_text, to_unicode(cov_text)),
]
for stem, lname in [("sec1-nat", "sec1Nat"), ("kernel-events", "kernelEvents")]:
    SUITES.append((lname, f"`skijack`'s corpus file `{stem}`",
                   (CORPUS / f"{stem}.ascii.ski").read_text(encoding="utf-8"),
                   (CORPUS / f"{stem}.unicode.ski").read_text(encoding="utf-8")))

