# ---------------------------------------------------------------- Scott.lean
lines = ['import Ski.Fuel', 'import Ski.Open', 'import Ski.Abs', 'open Term', '',
         '/-!', '# Scott constructors, as SKIjack compiles them',
         '',
         'Generated by `scripts/emit.py` from `skijack` 0.2.0; do not edit.  Each',
         'constructor is the closed term the compiler emits, and each elimination',
         'lemma is the reference reducer\'s own contraction sequence on symbolic',
         'arguments, re-run by the kernel (`iter_sound rfl`).  The continuation',
         'receives the fields as unreduced applications — `K ⬝ n ⬝ s` for `n` —',
         'which is what bracket abstraction produces and what every word-level',
         'proof has to reason through.  Each `_oelim` lemma is the same run on',
         'open terms (`oiter_sound rfl`), which decoding uses to probe at',
         'variables.  Each `_abs` theorem checks, by `rfl`, that `absN`',
         '(`Ski/Abs.lean`) of the constructor\'s source `λ fields conts. k_j fields`',
         'is the term `skijack` emitted.', '-/', '', 'namespace Scott', '']
for tname in ["nat", "item", "stack", "quot", "result"]:
    decl = types[tname]
    ctors = [c.name for c in decl.ctors]
    lines.append(f"-- {tname} === " + " | ".join(
        c.name + "".join(" " + f for f in c.fields) for c in decl.ctors))
    for c in decl.ctors:
        lines.append(f"def {c.name} : Term := {lean(e.terms[c.name])}")
    lines.append("")
    for c in decl.ctors:
        fields = [f"x{i}" for i in range(len(c.fields))]
        conts = [f"k{j}" for j in range(len(ctors))]
        shape, n = whnf_shape(e.terms[c.name], fields + conts)
        binders = " ".join(fields + conts)
        lhs = " ⬝ ".join([c.name] + fields + conts)
        lines.append(f"theorem {c.name}_elim ({binders} : Term) :")
        lines.append(f"    Steps ({lhs}) {shape} :=")
        lines.append(f"  iter_sound (k := {n}) rfl")
        lines.append("")
        t = e.terms[c.name]
        for a in fields + conts:
            t = App(t, Atom(a))
        r = run_level0(t, 10_000)
        assert r.steps == n
        lhsO = " ⬝ₒ ".join([f"{c.name}.toO"] + fields + conts)
        lines.append(f"theorem {c.name}_oelim ({binders} : OTerm) :")
        lines.append(f"    OSteps ({lhsO}) {leanO(r.term)} :=")
        lines.append(f"  oiter_sound (k := {n}) rfl")
        lines.append("")
        lines += ctor_abs(c.name, e.terms[c.name], len(c.fields), ctors.index(c.name), len(ctors))
lines += ["-- The kernel words, compiled (skilark.joy.COMPILED_KERNEL).  `wDip`, `wDo`",
          "-- and `wIfz` take the quotation eliminator `ap` first; `wLit` and `wQuote`",
          "-- take their literal first.  `wQcons`, `wCat` and `wUnit` build `quot`",
          "-- values, so their terms depend on the program's count of static",
          "-- quotations; these are the terms for a program with none.", ""]
for w in WORDS:
    lines.append(f"def {w} : Term := {lean(e.terms[w])}")
lines += ["", "-- The kernel's helpers: `add` (inlined into `wAdd`) and composition.", ""]
for w in HELPERS:
    lines.append(f"def {w} : Term := {lean(e.terms[w])}")
lines.append("")
lines.append("end Scott")
(OUT / "Scott.lean").write_text("\n".join(lines) + "\n", encoding="utf-8")

