"""Emit Lean from skijack: the Scott constructors of SKIlark's compiled kernel
with their elimination lemmas and the compiled kernel words (Ski/Scott.lean),
a small conformance corpus of terms with the reference reducer's
contraction counts plus a canonicity test per word (Ski/Corpus.lean), and
the quotation tables as Kit instances with their laws (Ski/Table.lean).  Run from the SKIlark venv:

    python scripts/emit.py

Every lemma is proved by `iter_sound rfl`: the kernel re-runs the same
contractions the reference reducer took, on symbolic arguments.
"""
import sys, pathlib
sys.path.insert(0, "/Users/neal/SKIlark")
import skijack
from skijack.run import run_level0
from aviary_kernel.terms import App, Atom
from skilark import joy
