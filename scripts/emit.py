def lean(t):
    if isinstance(t, Atom):
        return t.name
    return f"({lean(t.fn)} ⬝ {lean(t.arg)})"


def whnf_shape(term, args):
    """Apply `term` to fresh atoms and reduce to whnf on the host; return the
    shape (with the atoms as free variables) and the contraction count."""
    t = term
    for a in args:
        t = App(t, Atom(a))
    r = run_level0(t, 10_000)
    assert r.status.name == "WHNF", r.status
    return lean(r.term), r.steps


