# ---------------------------------------------------------------- Table.lean
# Quotation tables: one Kit instance per compilation, with its laws, each a
# count of contractions the reference reducer takes on symbolic arguments.
LEAN_WORD = {"dup": ".dup", "swap": ".swap", "pop": ".pop", "cons": ".cons",
             "cat": ".cat", "unit": ".unit", "dip": ".dip", "i": ".i",
             "ifz": ".ifz", "+": ".add"}
SK = {"S", "K", "I"}


def step1(t):
    r = run_level0(t, 1)
    return r.term if r.steps == 1 else None


def count_until(t, done, limit=10_000):
    """Contractions from `t` until `done(t)` holds; fails if it never does."""
    for k in range(limit):
        if done(t):
            return k, t
        t2 = step1(t)
        assert t2 is not None, "reached a normal form first"
        t = t2
    raise AssertionError("no stop within limit")


def head_args(t):
    args = []
    while isinstance(t, App):
        args.append(t.arg)
        t = t.fn
    return t, args[::-1]


def stuck(t):
    h, _ = head_args(t)
    return isinstance(h, Atom) and h.name not in SK


def ap_(*ts):
    t = ts[0]
    for u in ts[1:]:
        t = App(t, u)
    return t


def stage(t, T):
    """Contractions to the next stop: an atom at the head, `RErr`, or `RVal`."""
    return count_until(t, lambda u: stuck(u) or u == T["RErr"]
                       or (isinstance(u, App) and u.fn == T["RVal"]))


def lean_words(ws, quot_index):
    out = []
    for w in ws:
        if isinstance(w, int):
            out.append(f".lit {w}")
        elif isinstance(w, list):
            out.append(f".quote (.stat {quot_index(w)})")
        else:
            out.append(LEAN_WORD[w])
    return "[" + ", ".join(out) + "]"


def n_term(X, ws, apx, quot_index):
    """`N` of Ski/Composition.lean, on the host."""
    T = X.terms
    def word(w):
        if isinstance(w, int):
            t = T["Zero"]
            for _ in range(w):
                t = App(T["Suc"], t)
            return App(T["wLit"], t)
        if isinstance(w, list):
            return App(T["wQuote"], T[f"Q{quot_index(w) + 1}"])
        t = T["w" + joy.KERNEL[w]]
        return App(t, apx) if w in ("dip", "i", "ifz") else t
    if not ws:
        return T["idW"]
    out = word(ws[-1])
    for w in reversed(ws[:-1]):
        out = App(App(T["seq"], word(w)), out)
    return out


def word_term(X, w, apx, quot_index):
    T = X.terms
    if isinstance(w, int):
        t = T["Zero"]
        for _ in range(w):
            t = App(T["Suc"], t)
        return App(T["wLit"], t)
    if isinstance(w, list):
        return App(T["wQuote"], T[f"Q{quot_index(w) + 1}"])
    t = T["w" + joy.KERNEL[w]]
    return App(t, apx) if w in ("dip", "i", "ifz") else t


def compiles_proof(X, ws, t, apx, quot_index):
    """A proof of `Compiles apx ws t`: one `iter_sound rfl` per `seq`, the
    continuation left for the kernel to supply."""
    T = X.terms
    if not ws:
        return f"iter_sound (k := {count_until(t, lambda u: u == T['idW'])[0]}) rfl"
    if len(ws) == 1:
        target = word_term(X, ws[0], apx, quot_index)
        return f"iter_sound (k := {count_until(t, lambda u: u == target)[0]}) rfl"
    head = word_term(X, ws[0], apx, quot_index)
    k, u = count_until(t, lambda u: isinstance(u, App) and isinstance(u.fn, App)
                       and u.fn.fn == T["seq"] and u.fn.arg == head)
    return f"⟨_, iter_sound (k := {k}) rfl, {compiles_proof(X, ws[1:], u.arg, apx, quot_index)}⟩"


def quotation_table(programs):
    """The compiler's static quotations for a program set, in hoisting order."""
    comp = joy._Compiler()
    for prog in joy._programs(programs, joy.DEFINITIONS).values():
        comp.body(prog)
    i = 0
    while i < len(comp.quots):
        comp.body(comp.quots[i])
        i += 1
    return comp.quots, (lambda q: comp.index[joy.words(q)] - 1)


def lt_absurd(n):
    return f"absurd h (by show ¬ (_ + {n} < {n}); omega)"


def by_index(n, arms, fallback):
    """`match k, hk with | 0, _ => … | n-1, _ => … | _ + n, h => absurd`."""
    if n == 0:
        return f"fun k hk => absurd hk (Nat.not_lt_zero k)" if fallback else None
    cases = "".join(f"\n      | {k}, _ => {arm}" for k, arm in enumerate(arms))
    return f"fun k hk => match k, hk with{cases}\n      | _ + {n}, h => {lt_absurd(n)}"


def emit_table(ns, doc, X, quots, qidx, names, programs, rows=None):
    T = X.terms
    n = len(quots)
    L = [f"namespace {ns}", "", f"/-! {doc} -/", ""]
    for k in range(n):
        L.append(f"def Q{k + 1} : Term := {lean(T[f'Q{k + 1}'])}")
    for field in ["QCons", "QUnit", "QThen", "wQcons", "wCat", "wUnit", "applyU"]:
        if names[field] == field:
            L.append(f"def {field} : Term := {lean(T[field])}")
    if names["QCons"] == "QCons":
        L.append("")
        m = n + 3
        for k in range(n):
            L += ctor_abs(f"Q{k + 1}", T[f"Q{k + 1}"], 0, k, m)
        L += ctor_abs("QCons", T["QCons"], 2, n, m)
        L += ctor_abs("QUnit", T["QUnit"], 1, n + 1, m)
        L += ctor_abs("QThen", T["QThen"], 1, n + 2, m)
    for k in range(n):
        L.append(f"def b{k + 1} : Term := {lean(T[f'b{k + 1}'])}")
    if n:
        L.append("")
    # the table as data, and its kit compiled from source, term for term
    body = "fun _ => []" if n == 0 else "fun k => match k with" + "".join(
        f" | {k} => {lean_words(quots[k], qidx)}" for k in range(n)) + " | _ => []"
    ref = lambda field: names[field] if names[field] != field else field
    L += [f"def table : Table := ⟨{n}, {body}⟩", ""]
    for k in range(n):
        L.append(f"theorem table_Qs{k} : table.Qs {k} = Q{k + 1} := rfl")
    for field in ["QCons", "QUnit", "QThen", "wQcons", "wCat", "wUnit", "applyU"]:
        L.append(f"theorem table_{field} : table.{field} = {ref(field)} := rfl")
    for k in range(n):
        L.append(f"theorem table_bodyT{k} : table.bodyT {k} = b{k + 1} := rfl")
    L += ["", "/-- Every static quotation's body is valid over the table. -/",
          f"theorem table_valid : table.Valid := {by_index(n, ['rfl' for _ in range(n)], True)}", "",
          "scoped instance kit : Kit := table.kit",
          "scoped instance elim : KitElim := table.kit_elim",
          "scoped instance words : KitWords := table.kit_words",
          "scoped instance apply : KitApply := table.kit_apply table_valid", ""]
    # programs whose quotations are all in this table
    for pname, src in programs.items():
        ws = joy.expand(joy.parse(src), joy.DEFINITIONS)
        apx = Atom("apT")
        prf = compiles_proof(X, ws, App(T["c" + pname], apx), apx, qidx)
        L += [f"def c{pname} : Term := {lean(T['c' + pname])}", "",
              f"/-- `{src}`: the compiled program compiles its words. -/",
              f"theorem c{pname}_compiles (apT : Term) :",
              f"    Compiles apT {lean_words(ws, qidx)} (c{pname} ⬝ apT) :=",
              f"  {prf}", ""]
    # the corpus rows are these programs, run with this table's applyU on the empty stack
    for pname in (programs if rows else []):
        assert T["u" + pname] == App(App(T["c" + pname], T["applyU"]), T["Empty"])
        L += [f"/-- The corpus row `{rows}_u{pname}` is `c{pname}` run with this table's `applyU`",
              "    on the empty stack. -/",
              f"theorem {rows}_u{pname}_eq : {rows}_u{pname} = c{pname} ⬝ Kit.applyU ⬝ encStack [] := rfl", ""]
    L += [f"end {ns}", ""]
    return L


