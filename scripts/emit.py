def post(t):
    """A term's postfix codes (`Front.codeOf`): its function, its
    argument, then 3."""
    res = []
    def go(t):
        if isinstance(t, Atom):
            res.append({"S": 0, "K": 1, "I": 2}[t.name])
        else:
            go(t.fn); go(t.arg); res.append(3)
    go(t)
    return res


def pack(cs):
    """Codes packed 25 to a number, base 6, each code plus one, least
    significant first (`Front.codeOf`)."""
    out = []
    for k in range(0, len(cs), 25):
        n = 0
        for c in reversed(cs[k:k + 25]):
            n = n * 6 + (c + 1)
        out.append(n)
    return out


def codes_of(ns):
    cs = [str(n) for n in ns]
    return "[\n" + ",\n".join("  " + ", ".join(cs[k:k + 32]) for k in range(0, len(cs), 32)) + "]"


def codes(text):
    cs = [str(ord(ch)) for ch in text]
    return "[\n" + ",\n".join("  " + ", ".join(cs[k:k + 24]) for k in range(0, len(cs), 24)) + "]"


def check_outcome(text, lexicon):
    """`None` when `skijack` with its checker compiles `text`, else the
    name of what it raised."""
    try:
        skijack.compile(text, lexicon=lexicon, check=True)
    except Exception as e:
        return type(e).__name__
    return None


