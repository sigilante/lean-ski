OUT = pathlib.Path(__file__).resolve().parent.parent / "Ski"


def lean(t):
    if isinstance(t, Atom):
        return t.name
    return f"({lean(t.fn)} ⬝ {lean(t.arg)})"


def leanO(t):
    """The same term as an open term (`Ski/Open.lean`): the combinators are
    `OTerm`'s, and the free atoms stay variables of the Lean statement."""
    if isinstance(t, Atom):
        return f"OTerm.{t.name}" if t.name in ("S", "K", "I") else t.name
    return f"({leanO(t.fn)} ⬝ₒ {leanO(t.arg)})"


def ctor_abs(name, term, arity, index, nconts):
    """The fidelity test of `absN` (Ski/Abs.lean) for one Scott constructor:
    its source is `λ fields conts. k_index fields`, variables numbered fields
    first.  The host checks aviary's own abstraction reproduces `term` first."""
    nv = arity + nconts
    src = Atom(f"v{arity + index}")
    for i in range(arity):
        src = App(src, Atom(f"v{i}"))
    t = src
    for v in reversed(range(nv)):
        t = bracket_abstract(f"v{v}", t)
    assert t == term, f"{name}: bracket abstraction of its source differs from skijack's term"
    body = f"OTerm.var {arity + index}"
    for i in range(arity):
        body = f"({body} ⬝ₒ OTerm.var {i})"
    xs = ", ".join(str(v) for v in range(nv))
    return [f"theorem {name}_abs : absN [{xs}] ({body}) = {name}.toO := rfl", ""]


def whnf_shape(term, args):
    """Apply `term` to fresh atoms and reduce to whnf on the host; return the
    shape (with the atoms as free variables) and the contraction count."""
    t = term
    for a in args:
        t = App(t, Atom(a))
    r = run_level0(t, 10_000)
    assert r.status.name == "WHNF", r.status
    return lean(r.term), r.steps


e = skijack.compile(joy.compiled({"p": "1 2 + dup +"}))

#: the compiled kernel words, in Joy's order
WORDS = ["wDup", "wSwap", "wPop", "wQcons", "wCat", "wUnit", "wDip", "wDo",
         "wIfz", "wLit", "wQuote", "wAdd"]

#: the kernel's helpers the proofs name: numeral addition (inlined into
